CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    slug VARCHAR(100) NOT NULL UNIQUE,
    description TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE watches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    brand VARCHAR(100) NOT NULL,
    slug VARCHAR(150) NOT NULL UNIQUE,
    tagline VARCHAR(255),
    description TEXT NOT NULL,
    category_id BIGINT NOT NULL,
    price DECIMAL(12, 2) NOT NULL,
    currency VARCHAR(3) NOT NULL DEFAULT 'USD',
    movement_type VARCHAR(50) NOT NULL,
    caliber VARCHAR(100),
    case_material VARCHAR(100) NOT NULL,
    case_diameter_mm DECIMAL(4, 1) NOT NULL,
    case_thickness_mm DECIMAL(4, 1),
    water_resistance_m INT NOT NULL,
    power_reserve_hours INT NOT NULL,
    crystal_material VARCHAR(100) NOT NULL,
    dial_color VARCHAR(100) NOT NULL,
    strap_material VARCHAR(100),
    functions TEXT,
    image_url VARCHAR(500) NOT NULL,
    is_featured BOOLEAN NOT NULL DEFAULT FALSE,
    status VARCHAR(20) NOT NULL DEFAULT 'PUBLISHED',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_watch_category FOREIGN KEY (category_id) REFERENCES categories(id)
);

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    display_name VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL DEFAULT 'ROLE_USER',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE wishlist_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    watch_id BIGINT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_wishlist_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_wishlist_watch FOREIGN KEY (watch_id) REFERENCES watches(id) ON DELETE CASCADE,
    CONSTRAINT uq_user_watch UNIQUE (user_id, watch_id)
);

-- Indexes for performance
CREATE INDEX idx_watches_slug ON watches(slug);
CREATE INDEX idx_watches_brand ON watches(brand);
CREATE INDEX idx_watches_category ON watches(category_id);
CREATE INDEX idx_watches_price ON watches(price);
CREATE INDEX idx_watches_status ON watches(status);
CREATE INDEX idx_users_email ON users(email);
CREATE INDEX idx_wishlist_user ON wishlist_items(user_id);
